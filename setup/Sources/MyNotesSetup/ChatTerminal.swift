import AppKit
import CryptoKit
import Foundation

enum ChatTerminal {
    static func configuration(script: URL, directory: URL) throws -> (name: String, data: Data) {
        func literal(_ value: String) throws -> String {
            let data = try JSONSerialization.data(withJSONObject: value, options: [.fragmentsAllowed, .withoutEscapingSlashes])
            return String(decoding: data, as: UTF8.self)
        }
        let quoted = "'" + script.path.replacingOccurrences(of: "'", with: "'\\''") + "'"
        let text = try "# Generated by MyNotes\nname = \"MyNotes chat\"\ntitle = \"MyNotes\"\n\n[[panes]]\nid = \"chat\"\ntype = \"terminal\"\ndirectory = " + literal(directory.path) + "\ncommands = [" + literal("exec /bin/zsh " + quoted) + "]\n"
        let data = Data(text.utf8)
        let digest = SHA256.hash(data: data).prefix(8).map { String(format: "%02x", $0) }.joined()
        return ("mynotes_chat_" + digest, data)
    }

    @MainActor static func open(script: URL, directory: URL) throws {
        guard NSWorkspace.shared.urlForApplication(withBundleIdentifier: "dev.warp.Warp-Stable") != nil else {
            NSWorkspace.shared.open(script)
            return
        }
        let config = try configuration(script: script, directory: directory)
        let folder = FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".warp/tab_configs")
        try FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        let path = folder.appendingPathComponent(config.name + ".toml")
        if FileManager.default.fileExists(atPath: path.path) {
            guard try Data(contentsOf: path) == config.data else {
                throw NSError(domain: "MyNotes", code: 2, userInfo: [NSLocalizedDescriptionKey: "La configurazione Warp di MyNotes è stata modificata. Conservata senza sovrascriverla: " + path.path])
            }
        } else {
            try config.data.write(to: path, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: path.path)
        }
        guard let url = URL(string: "warp://tab_config/" + config.name), NSWorkspace.shared.open(url) else {
            throw NSError(domain: "MyNotes", code: 2, userInfo: [NSLocalizedDescriptionKey: "Impossibile aprire la chat in Warp."])
        }
    }
}
