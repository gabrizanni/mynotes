/** "Lezione 7", "Lezioni 5–7", "Lezioni 3, 5 e 7". */
function lessonsLabel(numbers: readonly number[]): string {
  if (numbers.length === 1) return `Lezione ${numbers[0] ?? ""}`;
  const first = numbers[0] ?? 0;
  const consecutive = numbers.every((n, index) => n === first + index);
  if (consecutive && numbers.length > 2) return `Lezioni ${first}–${numbers[numbers.length - 1] ?? first}`;
  return `Lezioni ${new Intl.ListFormat("it", { type: "conjunction" }).format(numbers.map(String))}`;
}

