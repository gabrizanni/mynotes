/** "Lesson 7", "Lessons 5–7", "Lessons 3, 5 and 7". Numbers arrive sorted. */
function lessonsLabel(numbers: readonly number[]): string {
  if (numbers.length === 1) return `Lesson ${numbers[0] ?? ""}`;
  const first = numbers[0] ?? 0;
  const consecutive = numbers.every((n, index) => n === first + index);
  if (consecutive && numbers.length > 2) return `Lessons ${first}–${numbers[numbers.length - 1] ?? first}`;
  return `Lessons ${new Intl.ListFormat("en", { type: "conjunction" }).format(numbers.map(String))}`;
}

